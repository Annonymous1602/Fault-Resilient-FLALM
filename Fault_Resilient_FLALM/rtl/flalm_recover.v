module flalm_recover #(
    parameter W  = 128,
    parameter NW = 8
) (
    input  wire clk,
    input  wire rst,

    // Host loads original X, Y and M before starting.
    input  wire host_we,
    input  wire [$clog2(4*NW)-1:0] host_addr,
    input  wire [W-1:0] host_data,

    input  wire start,
    input  wire [$clog2(NW+1)-1:0] len,
    input  wire smm_en,
    input  wire [W-1:0] mp,

    output wire busy,
    output wire done,
    output wire result_valid,
    output wire recovery_success,
    output wire recovery_failed,
    output reg  fault_seen,
    output wire z_sel,

    // Authorized Montgomery result readback.
    input  wire result_rd_en,
    input  wire [$clog2(NW)-1:0] result_rd_addr,
    output wire [W-1:0] result_rd_data
);

    localparam DEPTH = 4*NW;
    localparam AW = $clog2(DEPTH);
    localparam KW = $clog2(NW+1);

    localparam S_IDLE   = 3'd0;
    localparam S_LOAD   = 3'd1;
    localparam S_START  = 3'd2;
    localparam S_RUN    = 3'd3;
    localparam S_GOOD   = 3'd4;
    localparam S_FAIL   = 3'd5;

    reg [2:0] state;

    // Original X, Y and M are preserved.
    // Q-region contents are generated by FLALM.
    reg [W-1:0] shadow [0:3*NW-1];

    reg [AW-1:0] load_index;

    reg [KW-1:0] saved_len;
    reg saved_smm;
    reg [W-1:0] saved_mp;

    reg attempted_retry;
    reg attempt_fault;

    wire core_rst;
    wire core_start;

    wire core_busy;
    wire core_done;
    wire core_z_sel;
    wire core_fault;

    wire [AW-1:0] core_ram_a1;
    wire [AW-1:0] core_ram_a2;
    wire core_ram_we;
    wire [W-1:0] core_ram_d;

    wire [W-1:0] ram_o1;
    wire [W-1:0] ram_o2;

    wire [AW-1:0] selected_ram_a1;
    wire [AW-1:0] selected_ram_a2;
    wire selected_ram_we;
    wire [W-1:0] selected_ram_d;

    assign core_rst =
        rst || (state == S_IDLE) || (state == S_LOAD);

    assign core_start = (state == S_START);

    assign selected_ram_a1 =
        (state == S_LOAD) ? load_index : core_ram_a1;

    // The host owns the second RAM read port only
    // after successful completion.
    //
    // z_sel=0: result is stored in X region.
    // z_sel=1: result is stored in Y region.

    assign selected_ram_a2 =
        (state == S_GOOD && result_rd_en)
        ? (core_z_sel
           ? (NW + result_rd_addr)
           : result_rd_addr)
        : core_ram_a2;

    assign selected_ram_we =
        (state == S_LOAD) ? 1'b1 :
        (state == S_RUN) ? core_ram_we : 1'b0;

    assign selected_ram_d =
        (state == S_LOAD) ?
        shadow[load_index] :
        core_ram_d;

    flalm_core #(
        .W(W),
        .NW(NW)
    ) u_core (
        .clk(clk),
        .rst(core_rst),
        .start(core_start),
        .len(saved_len),
        .smm_en(saved_smm),
        .mp(saved_mp),

        .busy(core_busy),
        .done(core_done),
        .z_sel(core_z_sel),

        .security_fault_out(core_fault),

        .ram_a1(core_ram_a1),
        .ram_we(core_ram_we),
        .ram_d(core_ram_d),
        .ram_a2(core_ram_a2),
        .ram_o1(ram_o1),
        .ram_o2(ram_o2)
    );

    dpram #(
        .W(W),
        .DEPTH(DEPTH)
    ) u_ram (
        .clk(clk),
        .we(selected_ram_we),
        .a(selected_ram_a1),
        .d(selected_ram_d),
        .dpra(selected_ram_a2),
        .spo(ram_o1),
        .dpo(ram_o2)
    );

    assign busy =
        (state == S_LOAD) ||
        (state == S_START) ||
        (state == S_RUN);

    assign done =
        (state == S_GOOD) ||
        (state == S_FAIL);

    assign result_valid = (state == S_GOOD);

    assign recovery_success =
        (state == S_GOOD) && attempted_retry;

    assign recovery_failed = (state == S_FAIL);

    assign z_sel = core_z_sel;

    // Fail-closed external result readback.
    //
    // During execution, retry, or failure,
    // this interface always returns zero.

    assign result_rd_data =
        (state == S_GOOD &&
         result_rd_en &&
         result_rd_addr < NW)
        ? ram_o2
        : {W{1'b0}};

    always @(posedge clk) begin

        if (host_we && state == S_IDLE &&
            host_addr < 3*NW) begin

            shadow[host_addr] <= host_data;

        end

        if (rst) begin

            state <= S_IDLE;
            load_index <= 0;

            saved_len <= 0;
            saved_smm <= 0;
            saved_mp <= 0;

            attempted_retry <= 0;
            attempt_fault <= 0;
            fault_seen <= 0;

        end else begin

            case (state)

                S_IDLE: begin

                    if (start && !host_we &&
                        len != 0 && len <= NW) begin

                        saved_len <= len;
                        saved_smm <= smm_en;
                        saved_mp <= mp;

                        attempted_retry <= 0;
                        attempt_fault <= 0;
                        fault_seen <= 0;

                        load_index <= 0;
                        state <= S_LOAD;

                    end

                end

                S_LOAD: begin

                    if (load_index == 3*NW-1) begin

                        load_index <= 0;
                        attempt_fault <= 0;
                        state <= S_START;

                    end else begin

                        load_index <= load_index + 1'b1;

                    end

                end

                S_START: begin

                    state <= S_RUN;

                end

                S_RUN: begin

                    if (core_fault) begin

                        attempt_fault <= 1;
                        fault_seen <= 1;

                    end

                    if (core_done) begin

                        if (core_fault || attempt_fault) begin

                            fault_seen <= 1;

                            if (!attempted_retry) begin

                                attempted_retry <= 1;
                                load_index <= 0;
                                state <= S_LOAD;

                            end else begin

                                state <= S_FAIL;

                            end

                        end else begin

                            state <= S_GOOD;

                        end

                    end

                end

                S_GOOD: begin
                    // Result remains authorized until reset.
                end

                S_FAIL: begin
                    // Fail closed after the retry limit.
                end

                default: begin
                    state <= S_FAIL;
                end

            endcase

        end

    end

endmodule
